#!/usr/bin/env python3
"""Struktur S für die Ursachenanalyse #405 (siehe ansatz.md, Abschnitt 5).

Rein mechanisch aus Git und den Exporten. Deutet nichts.

Aufruf (Repo-Wurzel eines vollständigen, nicht flachen Klons mit refs/pr/*):
    python3 struktur.py <repo> <prs.tsv> <export/issues> > struktur.md

prs.tsv: nummer, state, merged_at, created_at, head_ref, titel (REST-API, alle PRs)
"""
import collections
import datetime as dt
import re
import subprocess
import sys
from pathlib import Path

REPO, PRS, ISSUES = sys.argv[1], sys.argv[2], Path(sys.argv[3])

STEUERUNG = {"ARBEITSPLAN.md", "GEGENLESUNG.md", "MILESTONES.md", "README.md"}


def bereich(pfad: str) -> str:
    """Zuordnung Pfad -> Bereich. Eine Wahl, offengelegt in struktur.md."""
    top = pfad.split("/", 1)[0]
    name = pfad.rsplit("/", 1)[-1]
    if top == "projects":
        return "P" if name in STEUERUNG else "F"
    if top in ("corpus", "entities", "palaeography"):
        return "F"
    if top == "source-entry":
        return "F" if name.endswith(".tsv") else "V"
    if top == "methodology" or pfad in ("GOVERNING_OBJECTIVE.md", "AGENTS.md", "DECISIONS.md"):
        return "M"
    if top in ("tools", "tests", ".github"):
        return "C"
    return "V"  # engineering, requirements, docs, templates, README, MILESTONES, SPICKZETTEL, .agents, sonstiges


def neuer_pfad(p: str) -> str:
    if "=>" not in p:
        return p
    m = re.match(r"(.*)\{(.*) => (.*)\}(.*)", p)
    if m:
        return (m.group(1) + m.group(3) + m.group(4)).replace("//", "/")
    return p.split(" => ")[1]


def git(*args):
    return subprocess.run(["git", "-C", REPO, *args], capture_output=True, text=True, check=True).stdout


def woche(datum: str) -> str:
    d = dt.date.fromisoformat(datum[:10])
    montag = d - dt.timedelta(days=d.weekday())
    return montag.isoformat()


def numstat(revspec):
    """-> Liste (sha, datum, {bereich: plus})"""
    out = git("log", *revspec, "-M", "--no-merges", "--numstat", "--format=@@%h %aI")
    res, cur = [], None
    for line in out.splitlines():
        if line.startswith("@@"):
            sha, datum = line[2:].split()
            cur = (sha, datum, collections.Counter())
            res.append(cur)
        elif line.strip() and cur:
            plus, _minus, pfad = line.split("\t", 2)
            if plus == "-":
                continue
            cur[2][bereich(neuer_pfad(pfad))] += int(plus)
    return res


# --- 1. Zeilen je Woche: main ---
main = numstat(["origin/main"])

# --- 2. Zeilen je Woche: nicht übernommene PRs (offen oder ohne Merge geschlossen) ---
prs = [l.split("\t") for l in Path(PRS).read_text().splitlines() if l.strip()]
unmerged = [p for p in prs if not p[2]]
merged = [p for p in prs if p[2]]
def ref_da(r):
    return subprocess.run(["git", "-C", REPO, "rev-parse", "--verify", "-q", r], capture_output=True).returncode == 0
excl = ["--not", "origin/main"] + [f"refs/pr/{p[0]}" for p in merged if ref_da(f"refs/pr/{p[0]}")]
unmerged = [p for p in unmerged if ref_da(f"refs/pr/{p[0]}")]
offen = numstat([f"refs/pr/{p[0]}" for p in unmerged] + excl) if unmerged else []

# --- 3. Issues und PRs je Woche aus dem Export ---
items = []
for f in sorted(ISSUES.glob("*.md")):
    txt = f.read_text()
    kopf = txt.splitlines()[0]
    art = "PR" if kopf.startswith("# PR") else "Issue"
    m = re.search(r"angelegt (\S+)", txt)
    labels = re.search(r"^- Labels: (.*)$", txt, re.M).group(1)
    claude = bool(re.search(r"_Claude, Prüfer|Generated by \[Claude Code\]|Generated with \[Claude Code\]", txt))
    claude_text = bool(re.search(r"_Claude, Prüfer|Claude Code", txt.split("=== ", 1)[0].split("## Kommentare", 1)[0]))
    items.append(dict(nr=int(f.stem), art=art, datum=m.group(1), labels=labels,
                      rettung="rettung-eigentümer" in labels, claude=claude, claude_text=claude_text,
                      titel=kopf.split(": ", 1)[-1]))

wochen = collections.OrderedDict()
def w(d):
    k = woche(d)
    if k not in wochen:
        wochen[k] = dict(commits=0, main=collections.Counter(), offen=collections.Counter(),
                         issues=0, prs=0, claude=0, rettung=[])
    return wochen[k]

for sha, d, c in main:
    x = w(d); x["commits"] += 1; x["main"].update(c)
for sha, d, c in offen:
    w(d)["offen"].update(c)
for it in items:
    x = w(it["datum"])
    x["issues" if it["art"] == "Issue" else "prs"] += 1
    x["claude"] += it["claude_text"]
    if it["rettung"]:
        x["rettung"].append(it["nr"])

wochen = collections.OrderedDict(sorted(wochen.items()))

B = ["F", "P", "M", "V", "C"]
print("# Struktur S: Zeitachse der ganzen Laufzeit\n")
print("Erzeugt mechanisch mit `analyse/struktur.py` aus Git (`main` und alle PR-Köpfe) und dem Export der Issues und PRs (#1–#405). Keine Deutung.\n")
print("**Bereiche (Zuordnung ist eine Wahl):** F Forschung = `projects/**` außer Steuerdateien, `corpus/`, `entities/`, `source-entry/*.tsv` · P Projektsteuerung = `ARBEITSPLAN.md`, `GEGENLESUNG.md`, `MILESTONES.md`, `README.md` in `projects/` · M Methodik = `methodology/`, `GOVERNING_OBJECTIVE.md`, `AGENTS.md`, `DECISIONS.md` · V Verfahren und Engineering = `engineering/`, `requirements/`, `docs/`, `templates/`, `README.md`, `MILESTONES.md`, `SPICKZETTEL.md` und Übriges · C Code = `tools/`, `tests/`, `.github/`.\n")
print("**Gezählt:** hinzugefügte Zeilen, Umbenennungen erkannt (`-M`), Merge-Commits ausgelassen. `main` = übernommen. `offen` = Commits nur in nicht übernommenen PRs (offen oder ohne Merge geschlossen), ohne Commits, die über andere PRs nach `main` kamen. Zeilen sind ein grobes Maß: Eine TSV-Zeile mit einer Lesung und eine Zeile Regelprosa zählen gleich.\n")
print(f"Grundlage: {len(main)} Commits auf `main` (ohne Merges), {len(offen)} Commits in {len(unmerged)} nicht übernommenen PRs, {len(items)} Issues und PRs.\n")

print("## 1. Wochen\n")
print("| Woche ab | Commits | F | P | M | V | C | F-Anteil main | offen F | offen übrige | Issues | PRs | mit Claude-Signatur | Label `rettung-eigentümer` |")
print("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
anteile = []
for k, x in wochen.items():
    tot = sum(x["main"].values())
    ant = round(100 * x["main"]["F"] / tot) if tot else None
    anteile.append((k, ant, tot))
    of = x["offen"]["F"]; ou = sum(x["offen"].values()) - of
    print(f"| {k} | {x['commits']} | " + " | ".join(str(x['main'][b]) for b in B) +
          f" | {'' if ant is None else str(ant)+' %'} | {of} | {ou} | {x['issues']} | {x['prs']} | {x['claude']} | {', '.join('#'+str(n) for n in x['rettung'])} |")

print("\n## 2. Wendepunkte nach der vorab festgelegten Regel (ansatz.md, Abschnitt 5)\n")
print("Regel: Der Forschungsanteil an den auf `main` hinzugefügten Zeilen steigt oder fällt gegenüber der Vorwoche um mindestens 30 Prozentpunkte, oder Systemarbeit (V+C) setzt nach mindestens einer Woche ohne Systemarbeit wieder ein; dazu alle Ereignisse mit Label `rettung-eigentümer`. Wochen mit weniger als 200 hinzugefügten Zeilen gelten als zu klein für einen Anteil und werden übersprungen (Ergänzung zur Regel, vor der Auswertung festgelegt, damit Ein-Commit-Wochen keine Ausschläge erzeugen).\n")
print("| Woche ab | Anteil vorher | Anteil jetzt | Richtung |")
print("|---|---|---|---|")
prev = None
for k, ant, tot in anteile:
    if ant is None or tot < 200:
        continue
    if prev is not None and abs(ant - prev[1]) >= 30:
        print(f"| {k} | {prev[1]} % ({prev[0]}) | {ant} % | {'zur Forschung' if ant > prev[1] else 'zur Systemarbeit'} |")
    prev = (k, ant)
sys_wochen = [k for k, x in wochen.items() if x["main"]["V"] + x["main"]["C"] > 0]
print("\nWiedereinsetzen von Systemarbeit nach einer Woche Pause: " + (", ".join(
    k for i, k in enumerate(list(wochen)) if i > 0 and k in sys_wochen and list(wochen)[i-1] not in sys_wochen) or "keins") + ".")
ret = [it for it in items if it["rettung"]]
print("\nEreignisse mit Label `rettung-eigentümer`: " + ", ".join(f"#{it['nr']} ({it['datum'][:10]}, {it['art']})" for it in ret) + ".")

print("\n## 3. Wann entstanden Regeln, Werkzeuge und Abläufe (Fortschreibung der Systemkarte)\n")
print("Erster Commit je Datei auf `main` (mit Umbenennungen verfolgt nur innerhalb des Bereichs), für `methodology/`, `tools/`, `.github/workflows/`, `docs/`, Wurzeldateien und die Projekt-Steuerdateien. `engineering/catalog/artifacts.tsv` führt Engineering-Artefakte bis ENG-A-0122 (09.10.); hier stehen nur Dateien, die bis heute auf `main` liegen.\n")
out = git("log", "origin/main", "--diff-filter=A", "--no-merges", "--name-only", "--format=@@%ad", "--date=short")
erst = {}
d = None
for line in out.splitlines():
    if line.startswith("@@"):
        d = line[2:]
    elif line.strip():
        erst[line] = d  # log ist neu -> alt, letzter Eintrag = ältester
heute = set(git("ls-tree", "-r", "--name-only", "origin/main").splitlines())
def zeige(prefix, titel):
    rows = sorted((erst.get(p, "?"), p) for p in heute if p.startswith(prefix) or p == prefix)
    print(f"**{titel}** ({len(rows)}): " + "; ".join(f"`{p}` {d}" for d, p in rows) + "\n")
zeige("methodology/", "Methodik")
zeige("tools/", "Werkzeuge")
zeige(".github/", "GitHub-Abläufe")
zeige("docs/", "Abläufe in docs/")
for f in ["GOVERNING_OBJECTIVE.md", "AGENTS.md", "DECISIONS.md", "README.md", "MILESTONES.md", "SPICKZETTEL.md"]:
    print(f"- `{f}`: angelegt {erst.get(f, '?')}")
print()
zeige("projects/ssta-20578-nr-632/", "Nr. 632 auf main")

print("\n## 4. Umfang der Regeltexte über die Zeit\n")
print("Zeilen von `AGENTS.md` und `methodology/` insgesamt am letzten Commit jeder Woche auf `main`.\n")
print("| Woche ab | AGENTS.md | methodology/ | engineering/ (Dateien) | tests/ (Dateien) |")
print("|---|---|---|---|---|")
for k in wochen:
    ende = (dt.date.fromisoformat(k) + dt.timedelta(days=7)).isoformat()
    sha = git("rev-list", "-1", f"--before={ende}", "origin/main").strip()
    if not sha:
        continue
    def zeilen(p):
        try:
            return len(git("show", f"{sha}:{p}").splitlines())
        except subprocess.CalledProcessError:
            return 0
    tree = git("ls-tree", "-r", "--name-only", sha).splitlines()
    meth = sum(zeilen(p) for p in tree if p.startswith("methodology/"))
    print(f"| {k} | {zeilen('AGENTS.md')} | {meth} | {sum(p.startswith('engineering/') for p in tree)} | {sum(p.startswith('tests/') for p in tree)} |")

print("\n## 5. Erste Claude-Signatur\n")
cl = sorted((it["datum"], it["nr"]) for it in items if it["claude_text"])
print(f"Früheste Issue oder PR mit Claude-Signatur im Text: #{cl[0][1]} ({cl[0][0][:10]}); insgesamt {len(cl)} Einträge. Alle Einträge stammen vom Konto `esany`; unsignierte Einträge sind keinem Modell zuzuordnen.")
